const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const DATA_DIR = path.join(process.cwd(), '_data');
const OUTPUT_FILE = path.join(process.cwd(), 'api', '_generated_translations.js');
const SUPPORTED_LOCALES = ['en', 'es', 'de', 'fr', 'ru', 'it', 'tr', 'uk'];

const rulesByLang = {};
const sbByLang = {};

SUPPORTED_LOCALES.forEach((lang) => {
  const rulesPath = path.join(DATA_DIR, lang, 'rules.yml');
  if (fs.existsSync(rulesPath)) rulesByLang[lang] = yaml.load(fs.readFileSync(rulesPath, 'utf8'));

  const sbPath = path.join(DATA_DIR, lang, 'survival_battle.yml');
  if (fs.existsSync(sbPath)) sbByLang[lang] = yaml.load(fs.readFileSync(sbPath, 'utf8'));
});

const fileContent = `/** AUTO-GENERATED BY GITHUB ACTIONS */\nexport const RULES_DATA = ${JSON.stringify(rulesByLang, null, 2)};\nexport const SB_DATA = ${JSON.stringify(sbByLang, null, 2)};\n`;

fs.writeFileSync(OUTPUT_FILE, fileContent, 'utf8');
console.log(`✅ Translations generated at ${OUTPUT_FILE}`);